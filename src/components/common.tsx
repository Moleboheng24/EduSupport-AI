export function ResponsibleNotice({ className }: { className?: string }) {
  return (
    <div className={cn("flex gap-3 rounded-lg border border-review/40 bg-accent p-4 text-sm text-accent-foreground", className)}>
      <ShieldAlert className="mt-0.5 h-5 w-5 shrink-0 text-review" />
      <p>
        <strong>Responsible use:</strong> findings come from a transparent, rule-based demonstration method — not a validated
        prediction model. They are prompts for an educator's professional judgement, never labels. No action should be taken
        against a student based on this output.
      </p>
    </div>
  );
}

export function SyntheticNotice({ source }: { source: "synthetic" | "upload" }) {
  return (
    <div className="flex gap-3 rounded-lg border bg-secondary p-3 text-sm text-secondary-foreground">
      <Info className="mt-0.5 h-4 w-4 shrink-0" />
      <p>
        {source === "synthetic"
          ? "All records shown are synthetic demonstration data generated by the application. No real students are represented."
          : "Showing an uploaded CSV dataset. Use anonymised demonstration data only — never real names or identifiers."}
      </p>
    </div>
  );
}

